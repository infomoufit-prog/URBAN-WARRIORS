import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();let ok=0;
const check=(cond,msg)=>{if(!cond){console.error('FAIL',msg);process.exitCode=1;}else{ok++;console.log('PASS',msg)}};
const text=p=>fs.readFileSync(path.join(root,p),'utf8');
const exists=p=>fs.existsSync(path.join(root,p));
const index=JSON.parse(text('web/assets/guides/runtime-index.json'));
const active=index.entries.filter(x=>x.active!==false);
const territories=active.filter(x=>x.kind==='territorial');
check(index.version==='20144-r91-public-guides-r100-1','runtime index is R91/20144');
check(index.show_master===false,'legacy master dossier hidden from public UI');
check(index.entries.length===53,'historical index compatibility retained');
check(active.length===38,'exactly 38 public R100.1 guides active');
check(territories.length===19,'exactly 19 active territorial guides');
check(new Set(territories.map(x=>x.territory)).size===19,'territories are unique');
check(active.every(x=>x.edition==='R100.1'),'all active guides are R100.1');
check(active.every(x=>exists('web/'+x.pdf.replace(/^\.\//,''))),'every active public guide PDF exists');
check(active.every(x=>fs.readFileSync(path.join(root,'web/'+x.pdf.replace(/^\.\//,''))).subarray(0,5).toString()==='%PDF-'),'every active guide is a PDF');
check(index.manual_product?.price_minor===600&&index.manual_product?.currency==='EUR','manual individual reference price is 6 EUR');
check(index.manual_product?.included_plan==='premium','manual included in Premium');
check(index.manual_product?.public_asset===false&&index.manual_product?.status==='prepared_private','manual is private/prepared, not public asset');
check(exists('artifacts/manuals/KOMBAX_MANUAL_GESTION_DE_CLUBES_R100_1.pdf'),'full club manual exists as private artifact');
check(!exists('web/assets/guides/KOMBAX_MANUAL_GESTION_DE_CLUBES_R100_1.pdf'),'full manual absent from public web assets');
check(!exists('web/assets/manuals/KOMBAX_MANUAL_GESTION_DE_CLUBES_R100_1.pdf'),'manual absent from alternate public manuals path');
check(text('.gitignore').includes('artifacts/manuals/'),'private manual artifacts are ignored by Git');
check(fs.readdirSync(path.join(root,'artifacts/guides-r100-1/source')).filter(x=>x.endsWith('.md')).length===38,'38 public editable guide sources archived');
const builder=text('scripts/build-kombax-guides-r100-1.py');
check(!builder.includes('/home/claude'),'guide builder has no Claude absolute path dependency');
const guides=text('web/js/modules/guides.js');
check(guides.includes("filter(x=>x.active!==false)"),'guide UI filters inactive legacy entries');
check(guides.includes('data.show_master!==false'),'legacy master visibility is controlled');
check(guides.includes('manual_product'),'manual product card is data-driven');
check(!guides.includes('KOMBAX_MANUAL_GESTION_DE_CLUBES_R100_1.pdf'),'manual private PDF path is not exposed in runtime JS');
check(!/checkout|paymentIntent|stripe-checkout/i.test(guides),'manual card does not invent a digital checkout');
const a3=text('artifacts/guides-r100-1/source/A3_FEDERACIONES_Y_OFICIALIDAD.md');
const a4=text('artifacts/guides-r100-1/source/A4_LICENCIAS_DEPORTIVAS.md');
const c1=text('artifacts/guides-r100-1/source/C1_CLASIFICAR_Y_PLANIFICAR_UN_EVENTO.md');
const b3=text('artifacts/guides-r100-1/source/B3_SEGUROS_Y_RESPONSABILIDAD.md');
check(/(art[íi]culo|art\.)\s*79/i.test(a3),'officiality source references Ley 39/2022 art.79');
check(/(art[íi]culo|art\.)\s*49\.1/i.test(a4),'licence source references Ley 39/2022 art.49.1');
check(/393\/2007[^\n]{0,160}derogad/i.test(c1)||/derogad[^\n]{0,160}393\/2007/i.test(c1),'autoprotection guide marks RD 393/2007 repealed');
check(/Ley 5\/2025/i.test(b3)&&/BOE/i.test(b3),'insurance guide cites Ley 5/2025 via BOE');
const manual=text('artifacts/manuals/MANUAL_KOMBAX_GESTION_DE_CLUBES_R100_1.md');
check(/precio_referencia_eur:\s*6/i.test(manual),'manual source records 6 EUR reference price');
check(/incluido_en:\s*KOMBAX Premium/i.test(manual),'manual source records Premium inclusion');
check(!/(^|\n)#{1,4}\s*(autoevaluaci[oó]n|solucionario|actividades|objetivos de aprendizaje|dossier del alumnado|dossier del formador|banco de preguntas)/im.test(manual),'manual has no training/evaluation sections');
const publicNames=[];
for(const base of ['web','dist','android/app/src/main/assets/www']){
  const dir=path.join(root,base);
  if(!fs.existsSync(dir)) continue;
  const walk=d=>{for(const e of fs.readdirSync(d,{withFileTypes:true})){const p=path.join(d,e.name);if(e.isDirectory())walk(p);else publicNames.push(path.relative(dir,p).toLowerCase())}};walk(dir);
}
check(!publicNames.some(x=>/(dossier.*alumn|dossier.*formador|cuaderno.*formador|banco.*pregunta|gift|aiken)/i.test(x)),'no Claude training/formador/question-bank assets exposed publicly');
check(text('web/config.js').includes('build: 20144'),'web build is 20144');
check(text('android/app/build.gradle').includes('versionCode 20144'),'Android versionCode is 20144');
check(text('android/app/build.gradle').includes("versionName '2.0.0-rc.13-r91-public-guides-r100-1'"),'Android R91 versionName set');
console.log(`R91 PUBLIC GUIDES GATE: ${ok} checks passed`);
if(process.exitCode) process.exit(process.exitCode);
