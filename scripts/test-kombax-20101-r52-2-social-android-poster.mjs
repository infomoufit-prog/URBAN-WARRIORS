import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const repo=read('web/js/core/repositories.js');
const social=read('web/js/modules/kombax-social.js');
const debug=read('scripts/android-debug-qa.mjs');
const play=read('scripts/android-play-bundle.mjs');
let ok=0,fail=0;
const test=(name,condition)=>{if(condition){console.log('PASS',name);ok++;}else{console.error('FAIL',name);fail++;}};

test('media presentation resolver rejects empty objects as authoritative',repo.includes("function hasMediaPresentation(value)")&&repo.includes("Object.keys(value).length"));
test('generic media enrichment falls back when embedded presentation is empty',repo.includes("[field]:resolveMediaPresentation(x?.[field],map.get(String(x?.[idKey]||'')))"));
test('Social feed presentation lookup uses resolved media_id returned by v238',repo.includes("x.social_media_id||x.media_id")&&repo.includes("resolvedMediaIds"));
test('Social feed resolves both social_media and profile_media sources',repo.includes("readMediaPresentations('social_media',resolvedMediaIds)")&&repo.includes("readMediaPresentations('profile_media',resolvedMediaIds)"));
test('Social feed reconstructs social_media_id when resolved id belongs to social media',repo.includes("social_media_id:x.social_media_id||(isSocialMedia?x.media_id:null)"));
test('Social feed prefers actual framing/cover metadata over empty embedded JSON',repo.includes("resolveMediaPresentation(x.media_presentation,socialMediaMap.get(resolvedId),profileMediaMap.get(resolvedId))"));
test('Social video renderer applies poster URL',social.includes("p.media_cover_url")&&social.includes("poster=\"${esc(p.media_cover_url)}\""));
test('Social feed resolves cover through storage access layer',social.includes("cover_storage_path")&&social.includes("mediaAccessUrl(coverPath"));
test('Android QA artifact is explicitly R52.2',debug.includes('KOMBAX_20101_R52_2_SOCIAL_ANDROID_POSTER_FIX_DEBUG.apk'));
test('Google Play artifact is explicitly R52.2',play.includes('KOMBAX_20101_R52_2_SOCIAL_ANDROID_POSTER_FIX_GOOGLE_PLAY.aab'));
console.log(`R52.2 ${ok}/${ok+fail} ${fail?'FAIL':'PASS'}`);
if(fail)process.exit(1);
