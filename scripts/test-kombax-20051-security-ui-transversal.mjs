import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const fail=m=>{console.error('FAIL 20051 SECURITY UI TRANSVERSAL:',m);process.exit(1)};
const ok=(c,m)=>{if(!c)fail(m)};
const publicProfile=read('web/js/modules/public-profile.js');
const gateway=read('web/js/modules/gateway.js');
const admin=read('web/js/modules/admin.js');
const portal=read('web/js/modules/portal.js');
const hub=read('web/js/modules/club-kombax-hub.js');
const security=read('web/js/modules/account-security.js');
const cfg=read('web/config.js');
const sw=read('web/service-worker.js');
const idx=read('web/index.html');
const gradle=read('android/app/build.gradle');

ok(publicProfile.includes("import { openAuthenticatedPasswordChange } from './account-security.js'"),'perfil público reutiliza el flujo único de cuenta');
ok(publicProfile.includes('kx-public-account-security')&&publicProfile.includes('Seguridad y acceso'),'todo perfil público propio expone Seguridad y acceso sin discriminar tipo');
ok(publicProfile.includes("#kx-public-account-security")&&publicProfile.includes('openAuthenticatedPasswordChange'),'acción contextual abre el flujo único de contraseña');
ok(gateway.includes('data-kx-profile-security')&&gateway.includes("querySelectorAll('[data-kx-profile-security]')"),'cada identidad directa Competidor/Marca/Federación expone seguridad contextual');
ok(gateway.includes('kx-global-change-password'),'cuenta KOMBAX mantiene acceso global a seguridad');
ok(admin.includes('change-account-password'),'Miembro/Equipo/Gestor conservan seguridad desde Mi perfil');
ok(portal.includes('portal-change-password'),'portal Miembro/Alumno conserva seguridad');
ok(hub.includes("card('security','Seguridad y acceso'"),'Gestor/Coordinación conserva acceso desde Perfil del Club');
ok(security.includes("name:'current_password'")&&security.includes("name:'new_password'")&&security.includes("name:'new_password_repeat'"),'flujo único exige actual, nueva y repetición');
ok(!publicProfile.includes('updatePassword(')&&!gateway.includes('updatePassword('),'las vistas de perfil no implementan cambios de contraseña paralelos');
const build=Number(cfg.match(/build:\s*(\d+)/)?.[1]||0),android=Number(gradle.match(/versionCode\s+(\d+)/)?.[1]||0);
ok(build>=20051&&android>=20051,'web y Android comparten build 20051');
const refs=[...idx.matchAll(/\?v=(\d+)/g)].map(x=>Number(x[1]));const swBuild=Number(sw.match(/rc13-(\d+)/)?.[1]||0);
ok(refs.length>0&&refs.every(v=>v>=20051)&&swBuild>=20051,'cache busting y service worker mantienen piso 20051');
console.log('KOMBAX BUILD 20051 · security UI transversal: PASS');
