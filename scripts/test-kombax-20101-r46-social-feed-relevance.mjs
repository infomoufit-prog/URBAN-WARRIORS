import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const social=read('web/js/modules/kombax-social.js');
const repo=read('web/js/core/repositories.js');
const css=read('web/css/kombax-premium.css');
const sql=read('supabase/migrations/236_kombax_social_feed_relevance_r46.sql');
const checks=[];const ok=(name,cond)=>checks.push([name,Boolean(cond)]);
ok('primary action says Me interesa',social.includes('>Me interesa</span>')||social.includes('>Me interesa</b>'));
ok('R46 personal hide contract is superseded safely by R47 preference',(!social.includes('data-social-hide')&&social.includes('No me interesa'))||(social.includes('data-social-hide')&&social.includes('hidePost')));
ok('post menu moves secondary actions out of primary row',social.includes('kx-post-menu-popover')&&social.includes('kx-social-primary-actions'));
ok('primary row is preference comment share',/kx-social-primary-actions[\s\S]*(data-social-like|kx-interest-control)[\s\S]*data-social-comments[\s\S]*data-social-share/.test(social));
ok('mobile feed is continuous edge-to-edge',css.includes('.kombax-social-feed{margin-left:-14px;margin-right:-14px')&&css.includes('border-radius:0!important'));
ok('mobile media can use more viewport',css.includes('max-height:76vh'));
ok('repository preserves R46 relevance feed as active or fallback',repo.includes("app_kombax_social_feed_v236")&&repo.includes('p_cursor_score'));
ok('repository retains legacy fallback',repo.includes("app_kombax_social_feed_v085"));
ok('cursor carries relevance score',social.includes('score:last.relevance_score??null'));
ok('private hidden table is RPC only',sql.includes('kombax_social_ocultados_usuario')&&sql.includes('enable row level security')&&sql.includes('revoke all on public.kombax_social_ocultados_usuario'));
ok('feed excludes personally hidden posts',sql.includes('not exists(select 1 from public.kombax_social_ocultados_usuario'));
ok('ranking uses recency and engagement',sql.includes('likes_count')&&sql.includes('comentarios_count')&&sql.includes('saved_count')&&sql.includes('date_trunc(\'hour\',now())'));
ok('ranking uses author affinity',sql.includes('author_interest_count')&&sql.includes('author_saved_count'));
ok('hide gateway is idempotent',sql.includes("p_operation='kombax.social.ocultar'")&&sql.includes('on conflict do nothing'));
ok('hide does not mutate post global state',!sql.includes("set estado='oculta'"));
for(const [n,c] of checks)console.log(`${c?'PASS':'FAIL'} · ${n}`);
const fails=checks.filter(x=>!x[1]);
console.log(`\nR46 ${checks.length-fails.length}/${checks.length} PASS`);
if(fails.length)process.exit(1);
