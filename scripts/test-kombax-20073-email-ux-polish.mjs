import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const config=read('web/config.js');
const index=read('web/index.html');
const gradle=read('android/app/build.gradle');
const main=read('android/app/src/main/java/com/urbanwarriors/app/MainActivity.java');
const sw=read('web/service-worker.js');
const health=read('supabase/functions/health/index.ts');
const build=Number(config.match(/build:\s*(\d+)/)?.[1]);
assert.ok(build>=20073);
assert.equal(Number(gradle.match(/versionCode\s+(\d+)/)?.[1]),build);
assert.ok(index.includes(`v=${build}`));
assert.ok(main.includes(`KOMBAXApp/2.0.0-rc.13/${build}`));
assert.ok(sw.includes(String(build)));
assert.ok(health.includes(`build:${build}`));
assert.doesNotMatch(index,/urban01\.netlify\.app/);
console.log('KOMBAX 20073 email UX polish/build identity: PASS');
