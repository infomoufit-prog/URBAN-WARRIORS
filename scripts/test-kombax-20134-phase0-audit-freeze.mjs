import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
let n=0;const ok=(v,m)=>{assert.ok(v,m);n++;};
const cfg=read('web/config.js');
const sw=read('web/service-worker.js');
const idx=read('web/index.html');
const gradle=read('android/app/build.gradle');
const main=read('android/app/src/main/java/com/urbanwarriors/app/MainActivity.java');
const manager=read('android/app/src/main/java/com/urbanwarriors/app/KombaxTerminalManager.java');
const health=read('supabase/functions/health/index.ts');
const iosInfo=read('ios/KombaxIOS/Info.plist');
const iosProject=read('ios/project.yml');
const currentBuild=Number(cfg.match(/build:\s*(\d+)/)?.[1]||0);
ok(currentBuild>=20135,'web build remains monotonic above phase0');
ok(/kombax-build-20\d{3}/.test(sw),'service worker keeps explicit build marker');
ok((idx.match(/v=20\d{3}/g)||[]).length>=10,'cache busters remain versioned');
const androidBuild=Number(gradle.match(/versionCode\s+(\d+)/)?.[1]||0);
ok(androidBuild===currentBuild,'Android versionCode matches web build');
ok(/KOMBAXApp\/2\.0\.0-rc\.\d+\/20\d{3}/.test(main),'Android UA keeps release/build identity');
ok(!/BuildConfig\.DEBUG/.test(manager),'no generated BuildConfig dependency in Terminal manager');
ok(/ApplicationInfo\.FLAG_DEBUGGABLE/.test(manager),'debug/simulated reader derives from ApplicationInfo');
ok(health.includes(`build:${currentBuild}`),'health matches the current backend release marker');
ok(/CFBundleVersion<\/key><string>20\d{3}/.test(iosInfo),'iOS bundle build remains versioned');
ok(/CURRENT_PROJECT_VERSION:\s*20\d{3}/.test(iosProject),'iOS project build remains versioned');
ok(!/sk_(live|test)_[A-Za-z0-9]{10,}/.test([cfg,manager,main].join('\n')),'no Stripe secret in client/native source');
console.log(`KOMBAX Phase 0 audit freeze build 20134: ${n}/${n} PASS`);
