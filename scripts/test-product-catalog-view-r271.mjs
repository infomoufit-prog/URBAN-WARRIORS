import assert from 'node:assert/strict';
import {normalizeProductView,productViewKey,readProductView,writeProductView,productViewToolbar,bindProductView} from '../web/js/ui/product-catalog-view.js';
let n=0;const test=(label,fn)=>{fn();n++;};
const entries=new Map(),storage={getItem:k=>entries.get(k),setItem:(k,v)=>entries.set(k,v)};
const a={id:'a',club_id:'one'},b={id:'b',club_id:'one'},otherClub={id:'a',club_id:'two'};
test('unknown or injected mode rejected',()=>assert.equal(normalizeProductView('list" onclick="x'),'compact'));
test('new users default compact',()=>assert.equal(readProductView('material',a,storage),'compact'));
writeProductView('material','list',a,storage);
test('preference survives reopening',()=>assert.equal(readProductView('material',a,storage),'list'));
test('another account isolated',()=>assert.equal(readProductView('material',b,storage),'compact'));
test('another club isolated',()=>assert.equal(readProductView('material',otherClub,storage),'compact'));
test('showcase preference independent',()=>assert.equal(readProductView('showcase',a,storage),'compact'));
test('showcase exploration follows account across clubs',()=>assert.equal(productViewKey('showcase',a),productViewKey('showcase',otherClub)));
const blocked={getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}};
test('blocked storage does not prevent reading',()=>assert.equal(readProductView('material',a,blocked),'compact'));
test('blocked storage does not prevent switching',()=>assert.equal(writeProductView('material','large',a,blocked),'large'));
globalThis.localStorage=storage;
test('toolbar has three accessible buttons',()=>{const html=productViewToolbar('material',a);assert.equal((html.match(/type="button"/g)||[]).length,3);assert.ok(html.includes('aria-pressed="true"'));});
const grid={dataset:{},cards:['item-a','item-b']};
const buttons=['compact','large','list'].map(mode=>({dataset:{catalogView:mode},attributes:{},listeners:{},setAttribute(k,v){this.attributes[k]=v},addEventListener(k,fn){this.listeners[k]=fn}}));
const root={querySelectorAll:q=>q.includes('data-catalog-area')?[grid]:buttons};
bindProductView('material',a,root);
test('bind restores list mode',()=>assert.equal(grid.dataset.productView,'list'));
buttons[1].listeners.click();
test('switch updates only presentation',()=>{assert.equal(grid.dataset.productView,'large');assert.deepEqual(grid.cards,['item-a','item-b']);});
test('only selected button pressed',()=>assert.deepEqual(buttons.map(b=>b.attributes['aria-pressed']),['false','true','false']));
test('switch saved without a data query',()=>assert.equal(readProductView('material',a,storage),'large'));
console.log(`PASS ${n} catalog preference, account isolation and view-switch checks`);
