import fs from 'node:fs';
import assert from 'node:assert/strict';
import {classifyPwaEnvironment} from '../web/js/modules/pwa-install.js';
const read=f=>fs.readFileSync(new URL('../'+f,import.meta.url),'utf8');
const personal=read('web/js/ui/personal-navigation.js');
const app=read('web/js/app.js');
const admin=read('web/js/modules/admin.js');
const install=read('web/js/modules/pwa-install.js');
const manifest=JSON.parse(read('web/manifest.webmanifest'));
const index=read('web/index.html');
const sw=read('web/service-worker.js');
let count=0;
const check=(condition,label)=>{assert.ok(condition,label);count++;};
for(const role of ['direccion','coordinacion','secretaria','economia','comunicacion','monitor']){
  check(app.includes(`role==='${role}'`)&&app.includes("'help','install','profile'"),`Club ${role}: install present`);
}
check(app.includes("else ids=['dashboard'")&&app.includes("'help','install','profile'"),'Other club roles, including family/student, keep install route');
check(personal.includes('data-kx-install-app')&&personal.includes('kx-pwa-install-nav'),'All standalone identities get sidebar action');
check(personal.includes('kx-personal-install-mobile'),'All standalone identities get mobile header action');
check(personal.includes("requestPwaInstall()"),'PWA action is bound to install controller');
check(personal.includes("t('navigation.routes.install')"),'Install label reuses configured localized navigation');
check(app.includes('initPwaInstall();'),'PWA listener installed on boot for all identities');
check(!app.includes("window.addEventListener('beforeinstallprompt'"),'No duplicate direct install listener');
check(admin.includes("requestPwaInstall()"),'Mi Club install uses shared controller');
check(app.includes("'#dashboard'")&&app.includes('renderShell'),'Club router preserved');
check(install.includes('event.preventDefault()')&&install.includes('appinstalled'),'Install and installed events handled');
check(install.includes('const started=prompt.prompt();'),'Browser prompt starts synchronously inside interaction');
check(install.includes('navigator.standalone')===false&&install.includes('nav?.standalone'),'iOS installed state supported');
check(install.includes('Añadir a pantalla de inicio')&&install.includes('Safari'),'iOS manual install instructions');
check(install.includes('Chrome')&&install.includes('Instalar aplicación'),'Android manual install instructions');
check(install.includes('Android de KOMBAX'),'Native APK already-installed guidance');
check(install.includes('same')===false&&install.includes('no cambia tus permisos'),'Install does not modify account permissions');
check(manifest.display==='standalone'&&manifest.icons.length>=2,'Manifest is installable with icons');
check(sw.includes('pwa-r270')&&index.includes('20178-pwa-r270'),'PWA cache-busting for deployment');
check(!install.includes('location.href=')&&!install.includes('window.open('),'No forced redirects to installation');
const env=(userAgent,extra={})=>classifyPwaEnvironment({navigator:{userAgent,maxTouchPoints:0,standalone:false,...extra.navigator},window:{location:{hostname:'kombax.es',protocol:'https:',...extra.location},matchMedia:()=>({matches:false}),...extra.window}});
check(env('Mozilla/5.0 (iPhone; CPU iPhone OS 17_0)').ios,'iOS browser detection');
check(env('Mozilla/5.0 (Linux; Android 15)').android,'Android browser detection');
check(env('Mozilla/5.0 (Linux; Android 15)',{window:{UrbanWarriorsNative:{}}}).standalone,'Native wrapper avoids reinstall');
check(env('Mozilla/5.0 (iPhone)',{navigator:{standalone:true}}).standalone,'Installed iOS PWA detection');
check(env('Mozilla/5.0 (Linux; Android 15) Instagram').inAppBrowser,'In-app browser guidance');
check(!env('Mozilla/5.0 (Windows NT 10.0)',{location:{protocol:'http:',hostname:'example.com'}}).secure,'Insecure origins cannot install');
console.log(`KOMBAX PWA R270 checks: ${count}/${count} PASS`);
